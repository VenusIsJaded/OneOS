#!/bin/sh
# Regenerate switcher/patches/OneOSGuestLock.smali, the helper class that
# patches/guest_local_lock.py puts into the guest's services.jar, from its Java
# source. The Java file is the source of truth (and runs on a desktop JVM in
# scripts/test-guest-local-lock.py); the smali is checked in so the overlay
# build needs no compiler, and carries the source's hash so a stale copy fails
# that test. No signing key or third-party dependency.
#
# Usage: scripts/build-guest-lock-smali.sh   (APKTOOL=<apktool jar> to override)
set -eu
cd "$(dirname "$0")/.."
sdk=${ANDROID_HOME:?Set ANDROID_HOME to the Android SDK}
javac=${JAVA_HOME:+$JAVA_HOME/bin/}javac
pinned_platform=${ANDROID_PLATFORM_VERSION:-android-35}
pinned_bt=${ANDROID_BUILD_TOOLS_VERSION:-35.0.0}
if [ -f "$sdk/platforms/$pinned_platform/android.jar" ]; then
    jar="$sdk/platforms/$pinned_platform/android.jar"
elif [ "${ALLOW_UNPINNED_SDK:-0}" = 1 ]; then
    jar=$(find "$sdk/platforms" -name android.jar | LC_ALL=C sort -V | tail -1)
else
    echo "error: pinned Android platform $pinned_platform not found under $sdk/platforms (set ANDROID_PLATFORM_VERSION or ALLOW_UNPINNED_SDK=1)" >&2
    exit 1
fi
if [ -x "$sdk/build-tools/$pinned_bt/d8" ]; then
    d8="$sdk/build-tools/$pinned_bt/d8"
elif [ "${ALLOW_UNPINNED_SDK:-0}" = 1 ]; then
    d8=$(find "$sdk/build-tools" -name d8 | LC_ALL=C sort -V | tail -1)
else
    echo "error: pinned Android build-tools $pinned_bt not found under $sdk/build-tools (set ANDROID_BUILD_TOOLS_VERSION or ALLOW_UNPINNED_SDK=1)" >&2
    exit 1
fi
apktool=${APKTOOL:-$(ls mysticgsi/tools/apktool/*.jar 2>/dev/null | LC_ALL=C sort -V | head -1)}
[ -n "$jar" ] && [ -f "$jar" ] && [ -n "$d8" ] && [ -x "$d8" ] && [ -n "$apktool" ] && [ -f "$apktool" ] || {
    echo "error: missing android.jar, d8, or apktool jar" >&2
    exit 1
}
echo "build-udfps-smali toolchain: javac=$("$javac" -version 2>&1) d8=$d8 android.jar=$jar apktool=$apktool" >&2
name=${1:-OneOSUdfps}
case $name in OneOSUdfps|OneOSSehTouch|OneOSFpTouch) ;; *) echo "usage: $0 [OneOSUdfps|OneOSSehTouch|OneOSFpTouch]" >&2; exit 2 ;; esac
src=switcher/patches/$name.java
out=switcher/patches/$name.smali
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM
mkdir "$tmp/cls" "$tmp/dex"
"$javac" --release 17 -Xlint:all -Werror -classpath "$jar" -d "$tmp/cls" "$src"
[ "$(find "$tmp/cls" -name '*.class' | wc -l)" = 1 ] || { echo "$src must stay one class (no inner classes or lambdas)" >&2; exit 1; }
"$d8" --release --min-api 31 --lib "$jar" --output "$tmp/dex" "$tmp/cls/com/android/server/biometrics/sensors/fingerprint/aidl/$name.class"
(cd "$tmp/dex" && python3 -c 'import zipfile; z = zipfile.ZipFile("../helper.jar", "w", zipfile.ZIP_STORED); z.write("classes.dex"); z.close()')
java -jar "$apktool" d -q -f -r -o "$tmp/src" "$tmp/helper.jar"
got="$tmp/src/smali/com/android/server/biometrics/sensors/fingerprint/aidl/$name.smali"
[ -f "$got" ]
if grep -q -E 'invoke-custom|invoke-polymorphic|const-method-handle' "$got"; then
    echo "$src compiles to instructions the patched jars do not use" >&2; exit 1
fi
sum=$(sha256sum "$src" | cut -d' ' -f1)
{
    sed -n '1,/^\.source /p' "$got"
    echo
    echo "# OneOS: the guest's in-display fingerprint ($name). Generated by scripts/build-udfps-smali.sh $name"
    echo "# from $name.java (sha256 $sum);"
    echo "# do not edit, change the Java source and run the script again."
    sed '1,/^\.source /d' "$got"
} > "$tmp/out.smali"
mv "$tmp/out.smali" "$out"
echo "wrote $out"
